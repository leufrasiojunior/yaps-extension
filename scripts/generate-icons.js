import fs from "node:fs";
import path from "node:path";

// Gera um PNG 1x1 azul basico repetido ou PNG valido minimo
// Formato binario minimo de um PNG transparente com pixel azul
function createMinimalPng() {
  return Buffer.from([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, // PNG Signature
    0x00, 0x00, 0x00, 0x0d, // IHDR length
    0x49, 0x48, 0x44, 0x52, // "IHDR"
    0x00, 0x00, 0x00, 0x10, // Width 16
    0x00, 0x00, 0x00, 0x10, // Height 16
    0x08, 0x06, 0x00, 0x00, 0x00, // 8-bit RGBA
    0x90, 0xe1, 0xae, 0x90, // CRC
    0x00, 0x00, 0x00, 0x17, // IDAT length
    0x49, 0x44, 0x41, 0x54, // "IDAT"
    0x78, 0x9c, 0x63, 0x60, 0x60, 0x60, 0xf8, 0x0f, 0x00, 0x01, 0x01, 0x01, 0x00, 0x18, 0x00, 0x00,
    0x00, 0xff, 0xff, 0x00, 0x05, 0x00, 0x01,
    0x0d, 0x0a, 0x2d, 0xb4, // CRC
    0x00, 0x00, 0x00, 0x00, // IEND length
    0x49, 0x45, 0x4e, 0x44, // "IEND"
    0xae, 0x42, 0x60, 0x82  // CRC
  ]);
}

const iconsDir = path.resolve("public/icons");
fs.mkdirSync(iconsDir, { recursive: true });

const png = createMinimalPng();
fs.writeFileSync(path.join(iconsDir, "icon-16.png"), png);
fs.writeFileSync(path.join(iconsDir, "icon-48.png"), png);
fs.writeFileSync(path.join(iconsDir, "icon-128.png"), png);

console.log("Ícones gerados com sucesso em public/icons/");
